// Command spgen builds the pool of WASM variants.
//
//	go run ./cmd/spgen -n 4 -out dist -seed <hex>
//
// For each variant it derives the Spec from the pool seed, generates
// client/wasm/variant_gen.go with that Spec's constants inlined as code, and
// compiles client/wasm to <out>/<name>.wasm. It also copies the compiler's
// wasm_exec.js and client/js/sp.js into <out>. Run it from the module root.
// Re-run with a new seed (and restart the servers with it) to invalidate
// every reverse-engineered variant at once.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"statelessprotection/internal/vm"
)

func main() {
	n := flag.Int("n", 4, "number of variants in the pool")
	out := flag.String("out", "dist", "output directory")
	seedHex := flag.String("seed", os.Getenv("SP_POOL_SEED"), "pool seed, hex (>=16 bytes); empty = insecure dev seed")
	compiler := flag.String("compiler", "go", "go or tinygo")
	flag.Parse()

	seed := devSeed()
	if *seedHex != "" {
		var err error
		if seed, err = hex.DecodeString(*seedHex); err != nil || len(seed) < 16 {
			log.Fatal("spgen: -seed must be hex and at least 16 bytes")
		}
	} else {
		log.Print("spgen: WARNING using the built-in dev seed; set -seed or SP_POOL_SEED for real use")
	}
	if _, err := os.Stat(filepath.Join("client", "wasm", "main.go")); err != nil {
		log.Fatal("spgen: run from the module root")
	}
	outAbs, err := filepath.Abs(*out)
	check(err)
	check(os.MkdirAll(outAbs, 0o755))

	for i := 0; i < *n; i++ {
		spec := vm.DeriveSpec(seed, i)
		check(os.WriteFile(filepath.Join("client", "wasm", "variant_gen.go"), genSource(&spec), 0o644))
		target := filepath.Join(outAbs, vm.Name(seed, i)+".wasm")
		check(build(*compiler, target))
		st, err := os.Stat(target)
		check(err)
		log.Printf("spgen: variant %d -> %s (%d KB)", i, filepath.Base(target), st.Size()/1024)
	}

	check(copyFile(runtimeJS(*compiler), filepath.Join(outAbs, "wasm_exec.js")))
	check(copyFile(filepath.Join("client", "js", "sp.js"), filepath.Join(outAbs, "sp.js")))
}

func devSeed() []byte {
	s := sha256.Sum256([]byte("sp-dev-pool-seed"))
	return s[:]
}

func check(err error) {
	if err != nil {
		log.Fatal("spgen: ", err)
	}
}

// genSource renders the variant as code: the dispatch switch, register
// mapping and every constant are literals, so each .wasm differs in its
// instructions and not just in a data table.
func genSource(s *vm.Spec) []byte {
	var b bytes.Buffer
	b.WriteString("//go:build js && wasm\n\n// Code generated by spgen. DO NOT EDIT.\n\npackage main\n\nimport \"math/bits\"\n\n")
	fmt.Fprintf(&b, "var variantSalt = [16]byte{%s}\n\n", byteList(s.Salt[:]))
	fmt.Fprintf(&b, "var regPerm = [8]byte{%s}\n\n", byteList(s.RegPerm[:]))
	b.WriteString("func runProgram(r *[8]uint32, p []byte) {\n")
	b.WriteString("\tfor i := 0; i+6 <= len(p); i += 6 {\n")
	b.WriteString("\t\ta, b := regPerm[p[i+1]&7], regPerm[(p[i+1]>>3)&7]\n")
	fmt.Fprintf(&b, "\t\timm := (uint32(p[i+2]) | uint32(p[i+3])<<8 | uint32(p[i+4])<<16 | uint32(p[i+5])<<24) ^ %#08x\n", s.ImmMask)
	fmt.Fprintf(&b, "\t\tswitch (p[i] ^ %#02x) & 7 {\n", s.OpXor)
	for wire := 0; wire < vm.NumOps; wire++ {
		op := s.OpPerm[wire]
		body := strings.NewReplacer(
			"$K", fmt.Sprintf("%#08x", s.K[op]),
			"$T", fmt.Sprintf("%d", s.Rot[op]),
		).Replace(vm.OpBodies[op])
		fmt.Fprintf(&b, "\t\tcase %d:\n\t\t\t%s\n", wire, strings.ReplaceAll(body, "; ", "\n\t\t\t"))
	}
	b.WriteString("\t\t}\n\t}\n}\n\nvar _ = bits.RotateLeft32\n")
	src, err := format.Source(b.Bytes())
	check(err)
	return src
}

func byteList(p []byte) string {
	parts := make([]string, len(p))
	for i, v := range p {
		parts[i] = fmt.Sprintf("%#02x", v)
	}
	return strings.Join(parts, ", ")
}

func build(compiler, target string) error {
	var cmd *exec.Cmd
	switch compiler {
	case "go":
		cmd = exec.Command("go", "build", "-trimpath", "-ldflags=-s -w", "-o", target, "./client/wasm")
		cmd.Env = append(os.Environ(), "GOOS=js", "GOARCH=wasm")
	case "tinygo":
		cmd = exec.Command("tinygo", "build", "-target", "wasm", "-no-debug", "-opt=z", "-panic=trap", "-o", target, "./client/wasm")
	default:
		return fmt.Errorf("unknown compiler %q", compiler)
	}
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	return cmd.Run()
}

// runtimeJS locates the JS glue that matches the compiler.
func runtimeJS(compiler string) string {
	if compiler == "tinygo" {
		root, err := exec.Command("tinygo", "env", "TINYGOROOT").Output()
		check(err)
		return filepath.Join(strings.TrimSpace(string(root)), "targets", "wasm_exec.js")
	}
	root, err := exec.Command("go", "env", "GOROOT").Output()
	check(err)
	r := strings.TrimSpace(string(root))
	for _, p := range []string{filepath.Join(r, "lib", "wasm", "wasm_exec.js"), filepath.Join(r, "misc", "wasm", "wasm_exec.js")} {
		if _, err := os.Stat(p); err == nil {
			return p
		}
	}
	log.Fatal("spgen: wasm_exec.js not found under GOROOT")
	return ""
}

func copyFile(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	return os.WriteFile(dst, data, 0o644)
}
